/** 所有"认识的地名"（支持范围 + 其他已知城市 + 省份） */
const ALL_KNOWN = [...CITIES, ...OTHER_CITIES, ...PROVINCES]

/**
 * 从文本里识别"用户说的是哪个地区"。
 * @returns {{region:string, kind:'city'|'other-city'|'province'|'explicit'|'district', supported:boolean}}
 *   `supported` = 该地区是否在**本作品承诺的演示范围**（`CITIES`）内。
 */
export function detectRegion(text) {
  const t = String(text || '')
  // ① 支持范围内的城市（含主要演示范围）
  const city = CITIES.find((c) => t.includes(c))
  if (city) return { region: city, kind: 'city', supported: true }
  // ② 其他已知城市 —— **能识别出来，但不是我们的演示范围**（要如实说明，不能假装支持）
  const other = OTHER_CITIES.find((c) => t.includes(c))
  if (other) return { region: other, kind: 'other-city', supported: false }
  // ③ 省份
  const prov = PROVINCES.find((p) => t.includes(p))
  if (prov) return { region: prov, kind: 'province', supported: false }
  // ④ "XX市/地区/自治州/盟"这类显式地名（例如"保定市""喀什地区"）
  const m = t.match(/([\u4e00-\u9fa5]{2,6})(?:市|地区|自治州|盟)(?=[^\u4e00-\u9fa5]|$|有|哪|的|，|,|\s)/)
  if (m) {
    const name = m[1]
    if (!/(本|该|全|各|我|你|他|她|它|这|那|哪|省市|县区|城乡|城市|都市|超市|上市|门市|集市|夜市|股市)/.test(name)) {
      return { region: name, kind: 'explicit', supported: false }
    }
  }
  // ⑤ 区/县（仅在命中常见区县表时才采信）
  const m2 = t.match(/([\u4e00-\u9fa5]{2,4})(?:区|县)(?=[^\u4e00-\u9fa5]|$|有|哪|的|，|,|\s)/)
  if (m2 && DISTRICTS.some((d) => m2[1].includes(d) || d.includes(m2[1]))) {
    return { region: m2[1], kind: 'district', supported: false }
  }
  return { region: '', kind: '', supported: false }
}

/** 该名字是否是"我们认识的地名"（用于"识别出来了但要如实说明范围"） */
export function looksLikeRegion(name) {
  const n = String(name || '').trim()
  if (n.length < 2) return false
  return ALL_KNOWN.includes(n) || Boolean(detectRegion(n).region)
}

/** 对外口径：一句话说明支持范围（页面/回答/文档都用这一句，避免各处不一致） */
export function scopeSentence() {
  return `本作品的主要演示范围是 **${PRIMARY_CITY}**，可辐射 **${RADIATING_CITIES.join(' / ')}** 共 ${RADIATING_CITIES.length} 个城市。`
}
